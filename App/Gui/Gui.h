/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
//按键事件类型
typedef enum
{
  KEY_EVENT_NONE = 0,     //无事件
  KEY_EVENT_SHORT_PRESS,  //短按
  KEY_EVENT_LONG_PRESS,   //长按(>2s)
  KEY_EVENT_MAX
}EnumKeyEvent;

//按键编号
typedef enum
{
  KEY_ID_KEY1 = 0,   //模式切换
  KEY_ID_KEY2,       //加/启动
  KEY_ID_KEY3,       //减/停止
  KEY_ID_KEY4,       //保存
  KEY_ID_MAX
}EnumKeyId;

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void  InitGui(void);                       //初始化GUI模块
void  Gui_ProcessKeyEvent(u8 keyId, u8 evt); //处理按键事件
void  Gui_Refresh(void);                   //刷新当前页面显示（周期调用）
void  Gui_SwitchPage(u8 page);             //切换到指定页面
u8    Gui_GetCurrentPage(void);            //获取当前页面

