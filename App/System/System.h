#ifndef _SYSTEM_H_
#define _SYSTEM_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
//页面定义
#define PAGE_OUTPUT     0   //信号输出页
#define PAGE_MEASURE    1   //信号测量页
#define PAGE_SETTING    2   //参数设置页

//输出模式
#define OUTPUT_MODE_DAC_DC     0   //DAC直流
#define OUTPUT_MODE_DAC_WAVE   1   //DAC周期波形
#define OUTPUT_MODE_PWM        2   //PWM数字脉冲

//DAC直流档位
#define DAC_DC_LEVEL_1V        0   //1.0V
#define DAC_DC_LEVEL_2V        1   //2.0V

//测量模式
#define MEASURE_MODE_ADC       0   //ADC模拟测量
#define MEASURE_MODE_CAPTURE   1   //输入捕获频率测量

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
//系统全局状态结构体（参见解决方案框架3.3节）
typedef struct
{
  u8      page;            //当前页面: 0=输出, 1=测量, 2=设置
  u8      outputMode;      //输出模式: 0=DAC直流, 1=DAC波形, 2=PWM
  u8      dacDcLevel;      //DAC直流档位: 0=1.0V, 1=2.0V
  u8      pwmFreqIndex;    //PWM频率档位: 0=100Hz, 1=1kHz, 2=5kHz
  u8      pwmDutyIndex;    //PWM占空比档位: 0=25%, 1=50%, 2=75%
  u8      outputEnable;    //输出使能标志: 0=停止, 1=运行
  u8      measureMode;     //测量模式: 0=ADC模拟, 1=输入捕获频率
  u8      paramIndex;      //参数设置页当前选中项
  u32     adcValue;        //ADC最新采集值
  u32     freqValue;       //频率测量值(Hz)，0=无信号
  //进阶统计量
  u16     adcMax;          //ADC最大值
  u16     adcMin;          //ADC最小值
  float   adcAvg;          //平均电压(V)
  u16     adcPeakPeak;     //峰峰值
  u8      captureDuty;     //输入捕获占空比(%)
}SystemState_t;

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void  System_InitState(void);          //初始化系统状态（从Flash恢复参数）
void  System_LoadDefaults(void);       //加载默认参数（Flash无效时使用）
void  System_SafeShutdown(void);       //安全关闭所有输出（DAC=0, PWM停止, 使能清零）
u8    System_IsIWDGReset(void);        //判断本次复位是否由IWDG引起

//全局状态变量声明（定义在System.c中）
extern  SystemState_t  g_systemState;

#endif
