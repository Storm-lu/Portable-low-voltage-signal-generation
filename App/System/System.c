/*********************************************************************************************************
* 函数名称：System_LoadDefaults
* 函数功能：加载默认参数（Flash校验失败时使用）
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年08月
* 注    意：默认值须与验收档位一致
*********************************************************************************************************/
void  System_LoadDefaults(void)
{
  g_systemState.page          = PAGE_OUTPUT;
  g_systemState.outputMode    = OUTPUT_MODE_DAC_DC;
  g_systemState.dacDcLevel    = DAC_DC_LEVEL_1V;
  g_systemState.pwmFreqIndex  = PWM_FREQ_100HZ;
  g_systemState.pwmDutyIndex  = PWM_DUTY_50;
  g_systemState.outputEnable  = 0;
  g_systemState.measureMode   = MEASURE_MODE_ADC;
  g_systemState.paramIndex    = 0;
  g_systemState.adcValue      = 0;
  g_systemState.freqValue     = 0;
  //进阶统计量清零
  g_systemState.adcMax        = 0;
  g_systemState.adcMin        = 0;
  g_systemState.adcAvg        = 0.0f;
  g_systemState.adcPeakPeak   = 0;
  g_systemState.captureDuty   = 0;
}

/*********************************************************************************************************
* 函数名称：System_InitState
* 函数功能：初始化系统状态，尝试从Flash恢复参数，失败则加载默认值
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年08月
* 注    意：上电时调用；IWDG复位后亦应先关闭输出再恢复参数
*********************************************************************************************************/
void  System_InitState(void)
{
  //TODO(成员D): 从Flash加载参数，校验魔数
  Flash_LoadParams(&g_systemState);

  //复位后安全处理：关闭全部输出
  System_SafeShutdown();
}

/*********************************************************************************************************
* 函数名称：System_SafeShutdown
* 函数功能：安全关闭所有输出（DAC=0, PWM停止, 输出使能清零）
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年08月
* 注    意：IWDG复位后、系统启动时调用，防止残留输出
*********************************************************************************************************/
void  System_SafeShutdown(void)
{
  //TODO(成员D): 关闭DAC输出、停止PWM、清除输出使能标志
  PWM_Stop();
  g_systemState.outputEnable = 0;
}

/*********************************************************************************************************
* 函数名称：System_IsIWDGReset
* 函数功能：判断本次复位是否由独立看门狗引起
* 输入参数：void
* 输出参数：void
* 返 回 值：1=IWDG复位 0=其他复位源
* 创建日期：2026年08月
* 注    意：通过读取RCC_CSR标志判断
*********************************************************************************************************/
u8  System_IsIWDGReset(void)
{
  //TODO(成员D): 读取RCC_CSR的IWDGRSTF标志
  return IWDG_IsResetByWatchdog();
}
