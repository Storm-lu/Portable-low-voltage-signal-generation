#ifndef _PWM_H_
#define _PWM_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
#define PWM_FREQ_INDEX_MAX  3   //频率档位数：100Hz/1kHz/5kHz
#define PWM_DUTY_INDEX_MAX  3   //占空比档位数：25%/50%/75%

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
//PWM频率档位
typedef enum
{
  PWM_FREQ_100HZ = 0,   //100Hz  PSC=7199, ARR=99
  PWM_FREQ_1KHZ,        //1kHz   PSC=719,  ARR=99
  PWM_FREQ_5KHZ,        //5kHz   PSC=143,  ARR=99
  PWM_FREQ_MAX
}EnumPWMFreq;

//PWM占空比档位
typedef enum
{
  PWM_DUTY_25 = 0,      //25%   CCR1=25
  PWM_DUTY_50,          //50%   CCR1=50
  PWM_DUTY_75,          //75%   CCR1=75
  PWM_DUTY_MAX
}EnumPWMDuty;

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void  InitPWM(void);                //初始化PWM模块（TIM3 CH1，PA6）
void  PWM_SetFreq(u8 idx);          //设置频率档位  idx: 0=100Hz, 1=1kHz, 2=5kHz
void  PWM_SetDuty(u8 idx);          //设置占空比档位 idx: 0=25%, 1=50%, 2=75%
void  PWM_Start(void);              //启动PWM输出
void  PWM_Stop(void);               //停止PWM输出（输出低电平）
u8    PWM_IsRunning(void);          //查询PWM是否正在输出

#endif
