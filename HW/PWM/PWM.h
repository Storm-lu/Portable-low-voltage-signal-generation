/*********************************************************************************************************
* 模块名称：PWM.h
* 摘    要：PWM数字脉冲输出模块，基于TIM3 CH2(PB5)，支持三档频率与三档占空比切换
* 当前版本：1.0.0
* 作    者：成员B（信号发生模块）
* 完成日期：2026年08月
* 内    容：基础任务5——PWM数字脉冲发生
*           频率档位：100Hz / 1kHz / 5kHz
*           占空比档位：25% / 50% / 75%
* 注    意：计数速率=72MHz/(71+1)=1MHz；频率误差须 ≤ 2%；TIM3_CH2使用部分重映射输出至PB5
*           调试短接时输入端禁止配下拉，避免3.3V与0V直连烧片
**********************************************************************************************************
* 取代版本：TIM3 CH1(PA6)版本
* 修改内容：硬件迁移至TIM3 CH2 PB5；API统一为项目金标准接口；分频方式改为固定PSC=71，修改ARR调整频率
*********************************************************************************************************/
#ifndef _PWM_H_
#define _PWM_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
/*
 * PWM 频率选项。
 * 对应 ARR 值：{9999, 999, 199} -> {100Hz, 1kHz, 5kHz}
 */
typedef enum{
    PWM_FREQ_100Hz,
    PWM_FREQ_1KHz,
    PWM_FREQ_5KHz
} PWMFreq;

/*
 * PWM 占空比选项。
 * 对应千分比：{250, 500, 750} -> {25%, 50%, 75%}
 */
typedef enum{
    PWM_DUTY_25,
    PWM_DUTY_50,
    PWM_DUTY_75
} PWMDuty;

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
/*
 * 使用默认设置（1kHz，50% 占空比）初始化 PWM 系统。
 * 配置 TIM3 CH2 在 PB5 上，但不启动输出（CCR=0）。
 * 在 InitHardware() 中调用一次。
 */
void InitPWM(void);

/*
 * 以指定的频率和占空比启动 PWM 输出。
 * 配置定时器并使能输出。
 *
 * 参数 freq：PWMFreq 枚举值（100Hz / 1kHz / 5kHz）
 * 参数 duty：PWMDuty 枚举值（25% / 50% / 75%）
 *
 * 调用者：SignalOutput.c -> OutputChange()、SetSignalOutputType()
 */
void StartPWM(PWMFreq freq, PWMDuty duty);

/*
 * 停止 PWM 输出。将 CCR 设为 0，禁用定时器。
 *
 * 调用者：SignalOutput.c、Main.c
 */
void StopPWM(void);

/*
 * 运行中修改 PWM 频率（不重启定时器）。
 * 通过 TIM_SetAutoreload 更新 ARR，根据当前占空比重算 CCR。
 *
 * 参数 freq：新的 PWMFreq 枚举值
 *
 * 调用者：Settings.c -> SaveSettings()
 */
void SetPWMFreq(PWMFreq freq);

/*
 * 运行中修改 PWM 占空比。
 * 根据当前 ARR 和新占空比重算 CCR。
 *
 * 参数 duty：新的 PWMDuty 枚举值
 *
 * 调用者：Settings.c -> SaveSettings()
 */
void SetPWMDuty(PWMDuty duty);

#endif
