#ifndef _INPUT_CAPTURE_H_
#define _INPUT_CAPTURE_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
#define CAPTURE_NO_SIGNAL_TIMEOUT_MS  1000U  //无信号超时时间1s
#define CAPTURE_FREQ_MIN              100U   //最低可测频率100Hz
#define CAPTURE_FREQ_MAX              10000U //最高可测频率10kHz

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void    InitInputCapture(void);       //初始化输入捕获模块（TIM4 CH1，PB6）
u32     Capture_GetFreq(void);        //获取频率值(Hz)，返回0表示无信号
u8      Capture_HasSignal(void);      //是否有有效信号 1=有 0=无
u8      Capture_GetDuty(void);        //获取占空比(%)，0~100；进阶任务
void    Capture_ProcessTimeout(void); //1ms周期调用，处理无信号超时清零

#endif
