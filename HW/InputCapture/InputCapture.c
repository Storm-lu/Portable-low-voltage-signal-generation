/*********************************************************************************************************
* 函数名称：InitInputCapture
* 函数功能：初始化输入捕获模块，配置TIM4 CH1(PB6)为上升沿捕获
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年08月
* 注    意：PSC=71，计数频率1MHz；使能捕获中断
*********************************************************************************************************/
void  InitInputCapture(void)
{
  //TODO(成员C):
  //1. 使能TIM4与GPIOB时钟
  //2. 配置PB6为浮空/上拉输入
  //3. 配置TIM4时基：PSC=71, ARR=0xFFFF
  //4. 配置TIM4_CH1为输入捕获，上升沿触发
  //5. 使能捕获/更新中断，启动定时器
  s_freqValue  = 0;
  s_hasSignal  = 0;
  s_timeoutCnt = 0;
  s_captureDuty = 0;
}

/*********************************************************************************************************
* 函数名称：Capture_GetFreq
* 函数功能：获取当前频率测量值
* 输入参数：void
* 输出参数：void
* 返 回 值：频率值(Hz)，0表示无信号
* 创建日期：2026年08月
* 注    意：f = 1000000 / capture_diff（计数频率1MHz）
*********************************************************************************************************/
u32  Capture_GetFreq(void)
{
  return s_freqValue;
}

/*********************************************************************************************************
* 函数名称：Capture_HasSignal
* 函数功能：查询是否有有效信号
* 输入参数：void
* 输出参数：void
* 返 回 值：1=有信号 0=无信号
* 创建日期：2026年08月
* 注    意：无信号超时1s后返回0
*********************************************************************************************************/
u8  Capture_HasSignal(void)
{
  return s_hasSignal;
}

/*********************************************************************************************************
* 函数名称：Capture_GetDuty
* 函数功能：获取占空比测量值（进阶任务）
* 输入参数：void
* 输出参数：void
* 返 回 值：占空比 0~100
* 创建日期：2026年08月
* 注    意：进阶：上升沿+下降沿双捕获实现
*********************************************************************************************************/
u8  Capture_GetDuty(void)
{
  return s_captureDuty;
}

/*********************************************************************************************************
* 函数名称：Capture_ProcessTimeout
* 函数功能：处理无信号超时，需1ms周期调用
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年08月
* 注    意：超时1s无捕获则清除频率结果并标记无信号
*********************************************************************************************************/
void  Capture_ProcessTimeout(void)
{
  //TODO(成员C):
  //每次捕获到信号时在ISR中重置s_timeoutCnt=0
  //此处累加s_timeoutCnt，超过CAPTURE_NO_SIGNAL_TIMEOUT_MS则清零频率、置无信号
  if(s_hasSignal)
  {
    s_timeoutCnt++;
    if(s_timeoutCnt >= CAPTURE_NO_SIGNAL_TIMEOUT_MS)
    {
      s_freqValue = 0;
      s_hasSignal = 0;
      s_timeoutCnt = 0;
    }
  }
}
